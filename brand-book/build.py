def frag_type():
    out = []
    for role, r in T['type'].items():
        if role.startswith('$'):
            continue
        fam = 'display' if r['family'] == 'display' else 'text'
        extra = ''
        if r.get('transform'):
            extra += f';text-transform:{r["transform"]}'
        if r.get('numeric'):
            extra += f';font-variant-numeric:{r["numeric"]}'
        sizes = ' · '.join(f'{bp[0].upper()} {r[bp]["size"]} / {r[bp]["weight"]}' for bp in BPS)
        status = ' <span class="tag">provisional</span>' if r.get('status') == 'provisional' else ''
        dot = '<span class="dot" aria-hidden="true"></span>' if role == 'eyebrow' else ''
        out.append(
            f'<div class="type-row" data-reveal>'
            f'<div class="type-meta"><span class="t-index">{esc(role)}</span>{status}'
            f'<span class="t-caption muted">{"Chillax" if fam == "display" else "Sofia Sans"} · {esc(sizes)}</span>'
            f'<span class="t-caption muted">line {r["lineHeight"]} · tracking {esc(r["letterSpacing"])}</span>'
            f'<span class="t-caption">{esc(r.get("use", ""))}</span></div>'
            f'<div class="type-sample f-{fam}" contenteditable="true" spellcheck="false" '
            f'style="{type_css_vars(role)}{extra}">{dot}{SAMPLES.get(role, esc(role))}</div></div>')
    return '\n'.join(out)


