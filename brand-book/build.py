def render():
    tpl = open(os.path.join(HERE, 'template.html')).read()
    pages_dir = os.path.join(HERE, 'pages')
    pages = ''.join(open(os.path.join(pages_dir, f)).read() for f in sorted(os.listdir(pages_dir)) if f.endswith('.html'))
    tpl = tpl.replace('{{PAGES}}', pages)
    icons, n_icons = frag_icons()
    frags = {
        'META': frag_meta(),
        'TOKENS_CSS': esc(open(os.path.join(DS, 'tokens.css')).read()),
        'LOGOS': frag_logos(),
        'LOGO_FULL': frag_logo_inline('full'),
        'LOGO_WORDMARK': frag_logo_inline('wordmark'),
        'LOGO_SYMBOL': frag_logo_inline('symbol'),
        'COLORS': frag_colors(),
        'GRADIENTS': frag_gradients(),
        'CONTRAST': frag_contrast(),
        'TYPE': frag_type(),
        'SPACE': frag_space(),
        'RADIUS': frag_radius(),
        'BREAKPOINTS': frag_breakpoints(),
        'ICONS': icons,
        'ICON_COUNT': str(n_icons),
        'PHOTOS': frag_photos(),
        'PATTERNS': frag_patterns(),
        'MOTION': frag_motion(),
        'ACCEPT': frag_accept(),
        'WIDTHS': frag_widths(),
        'A11Y': frag_a11y(),
        'RULE_ENTRANCE': frag_rule('entrance'),
        'RULE_PIN': frag_rule('pin'),
        'RULE_ILLUSTRATION': frag_rule('illustration-text-min'),
        'BUTTON_ARROW': frag_component('button', 'arrow'),
        'BUTTON_USE': frag_component('button', 'use'),
        'BUTTON_GROUP': frag_component('button', 'group'),
        'CARD_GLASS_USE': frag_component('card-glass', 'use'),
        'ICON_STROKE': frag_component('icon', 'stroke'),
        'ICON_DOT': frag_component('icon', 'dot'),
        'PHOTO_RULE': esc(ASSETS['rules'][0]),
    }

    def sub(m):
        k = m.group(1)
        if k not in frags:
            raise KeyError(f'template marker {{{{{k}}}}} has no fragment')
        return frags[k]

    out = re.sub(r'\{\{([A-Z_]+)\}\}', sub, tpl)
    return '<!-- Generated by brand-book/build.py from template.html and design-system/*.json. Do not edit by hand. -->\n' + out


def render_artifact(page):
    """The same page as a claude.ai artifact body: CSS, fonts and script inline; images stay as files beside it."""
    import base64
    css = open(os.path.join(HERE, 'brand-book.css')).read() + '\n' + open(os.path.join(HERE, 'book.css')).read()
    def font(m):
        f = m.group(1)
        data = base64.b64encode(open(os.path.join(HERE, f), 'rb').read()).decode()
        mime = 'font/otf' if f.endswith('.otf') else 'font/ttf'
        return f'url("data:{mime};base64,{data}")'
    css = re.sub(r'url\("(assets/fonts/[^"]+)"\)', font, css)
    tokens = open(os.path.join(DS, 'tokens.css')).read()
    js = open(os.path.join(HERE, 'brand-book.js')).read()
    body = page.split('<body>', 1)[1].rsplit('</body>', 1)[0]
    body = body.replace('<script src="brand-book.js"></script>', f'<script>\n{js}\n</script>')
    title = re.search(r'<title>.*?</title>', page).group(0)
    return (f'{title}\n<meta name="robots" content="noindex">\n'
            f'<style>\n{tokens}\n{css}\n</style>\n{body}')


def main():
    check = '--check' in sys.argv
    stale = []
    for src, dst in plan_copies():
        target = os.path.join(OUT_ASSETS, dst)
        same = os.path.exists(target) and open(src, 'rb').read() == open(target, 'rb').read()
        if not same:
            if check:
                stale.append(dst)
            else:
                os.makedirs(os.path.dirname(target), exist_ok=True)
                shutil.copyfile(src, target)
    page = render()
    idx = os.path.join(HERE, 'index.html')
    current = open(idx).read() if os.path.exists(idx) else ''
    if page != current:
        if check:
            stale.append('index.html')
        else:
            open(idx, 'w').write(page)
    art = render_artifact(page)
    art_path = os.path.join(HERE, 'artifact.html')
    if (open(art_path).read() if os.path.exists(art_path) else '') != art:
        if check:
            stale.append('artifact.html')
        else:
            open(art_path, 'w').write(art)
    if check:
        if stale:
            print('Stale (run python3 brand-book/build.py):', ', '.join(stale))
            sys.exit(1)
